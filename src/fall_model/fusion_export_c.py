"""Trains the fused wrist + waist + barometer model and exports it as C arrays.

The threshold is set automatically: the highest one that misses at most 5% of falls when
every subject is scored by a model trained on the others. The deployed model is then
trained on all subjects. Writes src/FallDetector_trials/fall_model_fusion.h and
data/features/fusion_reference.csv for fusion_parity.py.

Usage: python fusion_export_c.py      (after fusion_windows.py)
"""
import numpy as np
import pandas as pd

from fusion_classify import MODELS, T, W, loso_scores, make_rf, threshold_at
from load_wrist import FEATURES, ROOT

MISS = 0.05
MODEL_H = ROOT / "src" / "FallDetector_trials" / "fall_model_fusion.h"
F = MODELS["wrist + waist + barometer"]
assert F[:14] == [c for c in W.columns if c.startswith("w_")] and F[-1] == "dh_m"

def fl(x):   # same formatting as export_c.py
    s = "%.9g" % x
    return s if any(c in s for c in ".en") else s + ".0"


def arr(name, typ, xs, fmt):
    return f"static const {typ} {name}[{len(xs)}] = {{\n" + ",".join(fmt % x for x in xs) + "\n};\n"


falls, nonfalls = loso_scores(F)
thr = round(float(threshold_at(falls, MISS)), 3)
fa = (nonfalls >= thr).mean()
dh_fill = float(W.dh_m.median())
X = W[F].fillna({"dh_m": dh_fill})
rf = make_rf().fit(X, W.label)

feat, th, lc, rc, val, roots = [], [], [], [], [], []
for est in rf.estimators_:
    t = est.tree_
    off = len(feat)
    roots.append(off)
    for n in range(t.node_count):
        leaf = t.children_left[n] == -1
        feat.append(-1 if leaf else int(t.feature[n]))
        th.append(0.0 if leaf else float(t.threshold[n]))
        lc.append(0 if leaf else off + int(t.children_left[n]))
        rc.append(0 if leaf else off + int(t.children_right[n]))
        v = t.value[n, 0]
        val.append(float(v[1] / v.sum()))

with open(MODEL_H, "w") as f:
    f.write("/* Generated by src/fall_model/fusion_export_c.py. Do not edit by hand. */\n"
            f"/* Trained on {len(T)} paired trials ({int(T.is_fall.sum())} falls) from {T.subject.nunique()} subjects; "
            f"{len(W)} impact windows. */\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define FF_N_TREES {len(roots)}\n#define FF_N_FEATURES {len(F)}\n#define FF_THRESHOLD {thr}f\n"
            f"#define FF_DH_FILL {fl(dh_fill)}f\n")
    f.write("/* feature order: " + ", ".join(F) + " */\n")
    f.write(arr("FF_ROOT", "uint16_t", roots, "%d") + arr("FF_FEAT", "int8_t", feat, "%d") +
            arr("FF_THR", "float", [fl(x) + "f" for x in th], "%s") +
            arr("FF_LEFT", "uint16_t", lc, "%d") + arr("FF_RIGHT", "uint16_t", rc, "%d") +
            arr("FF_VAL", "float", [fl(x) + "f" for x in val], "%s"))

ref = W.assign(p=rf.predict_proba(X)[:, 1]).sample(min(200, len(W)), random_state=1)
ref[["trial", "idx", "p"] + F].to_csv(FEATURES / "fusion_reference.csv", index=False)
print(f"threshold {thr} (leave one subject out: miss <= {MISS:.0%}, false alarms {fa:.1%})")
print("nodes:", len(feat), "approx flash KB:", round(len(feat) * 13 / 1024, 1))
