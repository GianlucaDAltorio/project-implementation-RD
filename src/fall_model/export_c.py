"""Train the deployed wrist model and export it as C arrays for the watch.

Fits the random forest (100 trees, depth 6) on the training and validation subjects with
the same settings as wrist_classify.py and writes the trees as flat arrays that
fall_detect.c walks with plain comparisons.

Outputs:
    src/FallDetector_trials/fall_model.h   trees and decision threshold (THR below)
    data/features/feature_order.csv        feature index used by the C code
    data/features/py_reference.csv         200 windows with Python probabilities,
                                           used by parity_test/parity_check.py

THR is the decision threshold compiled into the firmware.

Usage:
    python export_c.py
"""
from pathlib import Path

import pandas as pd
from sklearn.ensemble import RandomForestClassifier

from load_wrist import FEATURES, ROOT

THR = 0.30
MODEL_H = ROOT / "src" / "FallDetector_trials" / "fall_model.h"

W = pd.read_csv(FEATURES / "wrist_windows.csv")
meta = pd.read_csv(FEATURES / "features.csv")
meta = meta[meta.device == "Wrist"]
F = [c for c in W.columns if c not in ("file", "subject", "activity_id", "activity", "is_fall_trial", "t_s", "idx", "label")]
W["split"] = W.subject.map(meta.drop_duplicates("subject").set_index("subject").split)
dev = W[W.split != "test"]
rf = RandomForestClassifier(100, max_depth=6, min_samples_leaf=3, class_weight="balanced",
                            random_state=0, n_jobs=2).fit(dev[F], dev.label)

feat, thr, lc, rc, val, roots = [], [], [], [], [], []
for est in rf.estimators_:
    t = est.tree_
    off = len(feat)
    roots.append(off)
    for n in range(t.node_count):
        leaf = t.children_left[n] == -1
        feat.append(-1 if leaf else int(t.feature[n]))
        thr.append(0.0 if leaf else float(t.threshold[n]))
        lc.append(0 if leaf else off + int(t.children_left[n]))
        rc.append(0 if leaf else off + int(t.children_right[n]))
        v = t.value[n, 0]
        val.append(float(v[1] / v.sum()))


def fl(x):
    s = "%.9g" % x
    return s if any(c in s for c in ".en") else s + ".0"


def arr(name, typ, xs, fmt):
    return f"static const {typ} {name}[{len(xs)}] = {{\n" + ",".join(fmt % x for x in xs) + "\n};\n"


with open(MODEL_H, "w") as f:
    f.write("/* Generated by src/fall_model/export_c.py. Do not edit by hand. */\n"
            "#pragma once\n#include <stdint.h>\n")
    f.write(f"#define FM_N_TREES {len(roots)}\n#define FM_N_FEATURES {len(F)}\n#define FM_THRESHOLD {THR}f\n")
    f.write("/* feature order: " + ", ".join(F) + " */\n")
    f.write(arr("FM_ROOT", "uint16_t", roots, "%d") + arr("FM_FEAT", "int8_t", feat, "%d") +
            arr("FM_THR", "float", [fl(x) + "f" for x in thr], "%s") +
            arr("FM_LEFT", "uint16_t", lc, "%d") + arr("FM_RIGHT", "uint16_t", rc, "%d") +
            arr("FM_VAL", "float", [fl(x) + "f" for x in val], "%s"))

pd.DataFrame({"idx": range(len(F)), "name": F}).to_csv(FEATURES / "feature_order.csv", index=False)
dev.assign(p=rf.predict_proba(dev[F])[:, 1]).sample(200, random_state=1)[["file", "idx", "p"] + F] \
    .to_csv(FEATURES / "py_reference.csv", index=False)
print("features:", F)
print("nodes:", len(feat), "approx flash KB:", round(len(feat) * 13 / 1024, 1))
